import { useState, useCallback } from 'react';
import { useNavigate } from 'react-router-dom';
import { motion, AnimatePresence } from 'framer-motion';
import PageTransition from '../components/PageTransition';
import Card from '../components/ui/Card';
import Button from '../components/ui/Button';
import { useStore } from '../lib/store';
import { ChevronDown, ArrowLeft, Download, Sparkles, Loader2 } from 'lucide-react';

export default function Results() {
  const { currentResult } = useStore();
  const navigate = useNavigate();
  const [expandedSection, setExpandedSection] = useState<string | null>('report');
  const [isGeneratingPdf, setIsGeneratingPdf] = useState(false);

  if (!currentResult) {
    navigate('/dashboard');
    return null;
  }

  const toggleSection = (id: string) => {
    setExpandedSection(expandedSection === id ? null : id);
  };

  const typeLabel =
    currentResult.type === 'mens-skincare'
      ? "Men's Skincare"
      : currentResult.type === 'womens-skincare'
        ? "Women's Skincare"
        : 'Diet Plan';

  const handleSaveReport = useCallback(async () => {
    if (!currentResult?.report) return;
    setIsGeneratingPdf(true);

    try {
      // Dynamic import so html2pdf only loads when needed
      const html2pdfModule = await import('html2pdf.js');
      const html2pdf = html2pdfModule.default;

      const reportDate = new Date(currentResult.date).toLocaleDateString('en-US', {
        year: 'numeric',
        month: 'long',
        day: 'numeric',
      });

      // Build a self-contained HTML string styled to match the website theme
      const pdfContent = `
        <div style="font-family: 'Segoe UI', 'Helvetica Neue', Arial, sans-serif; color: #1F1F1F; background: #F6F3EE; padding: 40px 36px; min-height: 100%;">
          <!-- Header Bar -->
          <div style="background: linear-gradient(135deg, #6B7A5E 0%, #4F5C45 100%); border-radius: 16px; padding: 28px 32px; margin-bottom: 32px;">
            <div style="display: flex; justify-content: space-between; align-items: center;">
              <div>
                <h1 style="margin: 0 0 6px 0; font-size: 26px; font-weight: 700; color: #FFFFFF; letter-spacing: -0.5px;">
                  Dermaïa
                </h1>
                <p style="margin: 0; font-size: 12px; color: rgba(255,255,255,0.75); text-transform: uppercase; letter-spacing: 1.5px;">
                  AI-Powered Skincare & Nutrition
                </p>
              </div>
              <div style="background: rgba(255,255,255,0.2); border-radius: 12px; padding: 10px 18px; text-align: center;">
                <div style="font-size: 22px; font-weight: 700; color: #FFFFFF;">${currentResult.score}</div>
                <div style="font-size: 9px; color: rgba(255,255,255,0.7); text-transform: uppercase; letter-spacing: 1px;">Score</div>
              </div>
            </div>
          </div>

          <!-- Report Meta -->
          <div style="display: flex; justify-content: space-between; align-items: center; margin-bottom: 24px; padding: 0 4px;">
            <div>
              <span style="display: inline-block; background: rgba(107,122,94,0.12); color: #6B7A5E; font-size: 11px; font-weight: 600; padding: 4px 12px; border-radius: 20px; text-transform: uppercase; letter-spacing: 0.8px;">
                ${typeLabel} Report
              </span>
            </div>
            <span style="font-size: 12px; color: #6B6B6B;">${reportDate}</span>
          </div>

          <!-- Divider -->
          <div style="height: 1px; background: linear-gradient(to right, transparent, #E8DCCF, transparent); margin-bottom: 28px;"></div>

          <!-- Report Body -->
          <div style="background: rgba(255,255,255,0.7); border: 1px solid #E8DCCF; border-radius: 16px; padding: 28px 28px;">
            <div style="font-size: 13px; line-height: 1.8; color: #3A3A3A;">
              ${markdownToHtmlForPdf(currentResult.report)}
            </div>
          </div>

          <!-- Footer -->
          <div style="margin-top: 36px; padding-top: 20px; border-top: 1px solid #E8DCCF; display: flex; justify-content: space-between; align-items: center;">
            <div style="font-size: 10px; color: #6B6B6B;">
              Generated by <strong style="color: #6B7A5E;">Dermaïa AI</strong> · For informational purposes only
            </div>
            <div style="font-size: 10px; color: #6B6B6B;">
              ${reportDate}
            </div>
          </div>
        </div>
      `;

      const container = document.createElement('div');
      container.innerHTML = pdfContent;
      document.body.appendChild(container);

      const fileName = `DermaIA_${typeLabel.replace(/[^a-zA-Z]/g, '_')}_Report_${new Date().toISOString().slice(0, 10)}.pdf`;

      await html2pdf()
        .set({
          margin: 0,
          filename: fileName,
          image: { type: 'jpeg', quality: 0.98 },
          html2canvas: { scale: 2, useCORS: true, backgroundColor: '#F6F3EE' },
          jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' },
          pagebreak: { mode: ['avoid-all', 'css', 'legacy'] },
        })
        .from(container)
        .save();

      document.body.removeChild(container);
    } catch (error) {
      console.error('PDF generation failed:', error);
    } finally {
      setIsGeneratingPdf(false);
    }
  }, [currentResult]);

  return (
    <PageTransition className="relative z-10 min-h-screen pt-28 pb-16 px-6">
      <div className="max-w-3xl mx-auto">
        {/* Header */}
        <motion.div
          initial={{ opacity: 0, y: 16 }}
          animate={{ opacity: 1, y: 0 }}
          className="mb-8"
        >
          <button
            onClick={() => navigate('/dashboard')}
            className="flex items-center gap-2 text-sm text-charcoal-muted hover:text-charcoal transition-colors mb-6 cursor-pointer"
          >
            <ArrowLeft className="w-4 h-4" />
            Back to Dashboard
          </button>

          <div className="flex items-start justify-between flex-wrap gap-4">
            <div>
              <div className="flex items-center gap-3 mb-2">
                <Sparkles className="w-5 h-5 text-olive" />
                <span className="text-xs font-medium text-olive uppercase tracking-wider">
                  AI Analysis Complete
                </span>
              </div>
              <h1 className="font-display text-3xl font-bold text-charcoal">
                Your Personalized Report
              </h1>
            </div>
            <div className="flex items-center gap-3">
              {/* Score */}
              <div className="relative w-16 h-16">
                <svg className="w-full h-full -rotate-90" viewBox="0 0 36 36">
                  <circle cx="18" cy="18" r="15.5" fill="none" stroke="#E8DCCF" strokeWidth="2" />
                  <motion.circle
                    cx="18" cy="18" r="15.5" fill="none" stroke="#6B7A5E" strokeWidth="2"
                    strokeLinecap="round"
                    strokeDasharray={`${(currentResult.score / 100) * 97.4} 97.4`}
                    initial={{ strokeDasharray: '0 97.4' }}
                    animate={{ strokeDasharray: `${(currentResult.score / 100) * 97.4} 97.4` }}
                    transition={{ duration: 1.5, ease: [0.22, 1, 0.36, 1], delay: 0.3 }}
                  />
                </svg>
                <div className="absolute inset-0 flex items-center justify-center">
                  <span className="text-sm font-bold text-charcoal">{currentResult.score}</span>
                </div>
              </div>
            </div>
          </div>
        </motion.div>

        {/* Sections */}
        <div className="space-y-4">
          {/* AI Generated Report */}
          {currentResult.report && (
            <ExpandableSection
              id="report"
              title="AI Generated Report"
              expanded={expandedSection === 'report'}
              onToggle={() => toggleSection('report')}
              delay={0.1}
            >
              <div
                className="text-sm text-charcoal leading-relaxed derma-report prose prose-sm max-w-none"
                dangerouslySetInnerHTML={{ __html: markdownToHtml(currentResult.report) }}
              />
            </ExpandableSection>
          )}

          {/* Summary (for backwards compat) */}
          {currentResult.summary && !currentResult.report && (
            <ExpandableSection
              id="summary"
              title="Analysis Summary"
              expanded={expandedSection === 'summary'}
              onToggle={() => toggleSection('summary')}
              delay={0.15}
            >
              <p className="text-sm text-charcoal-muted leading-relaxed">
                {currentResult.summary}
              </p>
            </ExpandableSection>
          )}
        </div>

        {/* Actions */}
        <motion.div
          initial={{ opacity: 0, y: 16 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 0.6 }}
          className="flex flex-wrap gap-4 mt-8"
        >
          <Button onClick={() => navigate('/dashboard')}>
            Back to Dashboard
          </Button>
          <Button
            variant="outline"
            icon={isGeneratingPdf ? <Loader2 className="w-4 h-4 animate-spin" /> : <Download className="w-4 h-4" />}
            onClick={handleSaveReport}
            disabled={isGeneratingPdf}
          >
            {isGeneratingPdf ? 'Generating...' : 'Save Report'}
          </Button>
        </motion.div>
      </div>
    </PageTransition>
  );
}

function ExpandableSection({
  title,
  expanded,
  onToggle,
  children,
  delay = 0,
}: {
  id: string;
  title: string;
  expanded: boolean;
  onToggle: () => void;
  children: React.ReactNode;
  delay?: number;
}) {
  return (
    <motion.div
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ delay, duration: 0.5 }}
    >
      <Card glass className="overflow-hidden !p-0">
        <button
          onClick={onToggle}
          className="w-full flex items-center justify-between p-6 cursor-pointer"
        >
          <h3 className="font-display text-lg font-semibold text-charcoal">{title}</h3>
          <motion.div animate={{ rotate: expanded ? 180 : 0 }} transition={{ duration: 0.3 }}>
            <ChevronDown className="w-5 h-5 text-charcoal-muted" />
          </motion.div>
        </button>
        <AnimatePresence>
          {expanded && (
            <motion.div
              initial={{ height: 0, opacity: 0 }}
              animate={{ height: 'auto', opacity: 1 }}
              exit={{ height: 0, opacity: 0 }}
              transition={{ duration: 0.35, ease: [0.22, 1, 0.36, 1] }}
              className="overflow-hidden"
            >
              <div className="px-6 pb-6">{children}</div>
            </motion.div>
          )}
        </AnimatePresence>
      </Card>
    </motion.div>
  );
}

// Simple markdown to HTML converter (for on-screen rendering)
function markdownToHtml(md: string): string {
  const html = md
    .replace(/```(\w*)\n([\s\S]*?)```/g, '<pre class="bg-charcoal/5 rounded-lg p-3 my-2 overflow-x-auto text-xs"><code>$2</code></pre>')
    .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
    .replace(/\*(.*?)\*/g, '<em>$1</em>')
    .replace(/^### (.*$)/gm, '<h4 class="font-semibold text-charcoal mt-3 mb-1">$1</h4>')
    .replace(/^## (.*$)/gm, '<h3 class="font-display font-semibold text-charcoal mt-4 mb-1.5 text-base">$1</h3>')
    .replace(/^# (.*$)/gm, '<h2 class="font-display font-bold text-charcoal mt-4 mb-2 text-lg">$1</h2>')
    .replace(/^- (.*$)/gm, '<li class="ml-4 list-disc text-charcoal-muted">$1</li>')
    .replace(/^\* (.*$)/gm, '<li class="ml-4 list-disc text-charcoal-muted">$1</li>')
    .replace(/^\d+\. (.*$)/gm, '<li class="ml-4 list-decimal text-charcoal-muted">$1</li>')
    .replace(/\n\n/g, '<br/><br/>')
    .replace(/\n/g, '<br/>');
  return html;
}

// Markdown to HTML for PDF (uses inline styles instead of Tailwind classes)
function markdownToHtmlForPdf(md: string): string {
  const html = md
    .replace(/```(\w*)\n([\s\S]*?)```/g, '<pre style="background: #f5f0ea; border-radius: 8px; padding: 12px; margin: 8px 0; font-size: 11px; overflow-x: auto; font-family: monospace;"><code>$2</code></pre>')
    .replace(/\*\*(.*?)\*\*/g, '<strong style="color: #1F1F1F; font-weight: 600;">$1</strong>')
    .replace(/\*(.*?)\*/g, '<em>$1</em>')
    .replace(/^### (.*$)/gm, '<h4 style="font-weight: 600; color: #1F1F1F; margin-top: 16px; margin-bottom: 6px; font-size: 14px; border-left: 3px solid #6B7A5E; padding-left: 10px;">$1</h4>')
    .replace(/^## (.*$)/gm, '<h3 style="font-weight: 600; color: #1F1F1F; margin-top: 20px; margin-bottom: 8px; font-size: 16px; border-bottom: 1px solid #E8DCCF; padding-bottom: 6px;">$1</h3>')
    .replace(/^# (.*$)/gm, '<h2 style="font-weight: 700; color: #4F5C45; margin-top: 22px; margin-bottom: 10px; font-size: 18px;">$1</h2>')
    .replace(/^- (.*$)/gm, '<li style="margin-left: 16px; color: #3A3A3A; list-style-type: disc; margin-bottom: 4px;">$1</li>')
    .replace(/^\* (.*$)/gm, '<li style="margin-left: 16px; color: #3A3A3A; list-style-type: disc; margin-bottom: 4px;">$1</li>')
    .replace(/^\d+\. (.*$)/gm, '<li style="margin-left: 16px; color: #3A3A3A; list-style-type: decimal; margin-bottom: 4px;">$1</li>')
    .replace(/\n\n/g, '<br/><br/>')
    .replace(/\n/g, '<br/>');
  return html;
}
